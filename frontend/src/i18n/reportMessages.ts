export function reportT(
  lang: AppLanguage,
  key: ReportMessageKey,
  vars?: Record<string, string | number>,
): string {
  let text = (MESSAGES[lang] || EN)[key] || EN[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export function reportReasonLabel(lang: AppLanguage, reason: string): string {
  const key = REASON_KEY_BY_VALUE[reason];
  return key ? reportT(lang, key) : reason;
}
