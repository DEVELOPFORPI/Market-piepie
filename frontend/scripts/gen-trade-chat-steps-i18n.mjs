import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const LANGS = [
  'en', 'ko', 'zh', 'ja', 'es', 'pt', 'fr', 'de', 'id', 'vi', 'th', 'hi', 'ar', 'ru', 'tr',
  'it', 'pl', 'nl', 'fil', 'uk', 'bn', 'ms', 'sw', 'fa', 'ur',
];

function assertComplete(entries, name) {
  const keys = Object.keys(entries);
  for (const k of keys) {
    for (const lang of LANGS) {
      if (!entries[k][lang]) {
        console.error(`Missing ${lang} for ${name}.${k}`);
        process.exit(1);
      }
    }
  }
  return keys;
}

function writePack(fileBase, typeName, fnName, entries) {
  const keys = assertComplete(entries, fileBase);
  let out = `/* Auto-generated by scripts/gen-trade-chat-steps-i18n.mjs */
import type { AppLanguage } from '@/utils/languageStorage';

export type ${typeName} =
${keys.map((k) => `  | '${k}'`).join('\n')};

const MESSAGES: Record<AppLanguage, Record<${typeName}, string>> = {\n`;
  for (const lang of LANGS) {
    out += `  ${lang}: {\n`;
    for (const k of keys) {
      const v = entries[k][lang]
        .replace(/\\/g, '\\\\')
        .replace(/'/g, "\\'")
        .replace(/\r/g, '\\r')
        .replace(/\n/g, '\\n');
      out += `    ${k}: '${v}',\n`;
    }
    out += `  },\n`;
  }
  out += `};

export function ${fnName}(
  lang: AppLanguage,
  key: ${typeName},
  vars?: Record<string, string | number>,
): string {
  const raw = MESSAGES[lang]?.[key] ?? MESSAGES.en[key] ?? key;
  if (!vars) return raw;
  return Object.entries(vars).reduce(
    (s, [k, v]) => s.split('{' + k + '}').join(String(v)),
    raw,
  );
}
`;
  fs.writeFileSync(path.join(__dirname, `../src/i18n/${fileBase}.ts`), out, 'utf8');
  console.log('Wrote', fileBase + '.ts', keys.length, 'keys');
}

