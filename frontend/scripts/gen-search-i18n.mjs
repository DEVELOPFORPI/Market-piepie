const keys = Object.keys(entries);
for (const k of keys) {
  for (const lang of LANGS) {
    if (!entries[k][lang]) {
      console.error(`Missing ${lang} for ${k}`);
      process.exit(1);
    }
  }
}

let out = `/* Auto-generated by scripts/gen-search-i18n.mjs */
import type { AppLanguage } from '@/utils/languageStorage';

export type SearchMessageKey =
${keys.map((k) => `  | '${k}'`).join('\n')};

const SEARCH_MESSAGES: Record<AppLanguage, Record<SearchMessageKey, string>> = {\n`;

for (const lang of LANGS) {
  out += `  ${lang}: {\n`;
  for (const k of keys) {
    const v = entries[k][lang]
      .replace(/\\/g, '\\\\')
      .replace(/'/g, "\\'")
      .replace(/\r/g, '\\r')
      .replace(/\n/g, '\\n');
    out += `    ${k}: '${v}',\n`;
  }
  out += `  },\n`;
}
out += `};

export function searchT(
  lang: AppLanguage,
  key: SearchMessageKey,
  vars?: Record<string, string | number>,
): string {
  const raw = SEARCH_MESSAGES[lang]?.[key] ?? SEARCH_MESSAGES.en[key] ?? key;
  if (!vars) return raw;
  return Object.entries(vars).reduce(
    (s, [k, v]) => s.split('{' + k + '}').join(String(v)),
    raw,
  );
}
`;

fs.writeFileSync(path.join(__dirname, '../src/i18n/searchMessages.ts'), out, 'utf8');
